import { useMemo, useState } from 'react';
import { useTranslation } from 'react-i18next';
import { Link, useLocation } from 'wouter';
import type { Charge } from '@empirica/shared';
import { usePendingIds } from '../data/hooks.ts';
import { useNames } from '../data/names.ts';
import { formatDate } from '../i18n/index.ts';
import { useScope } from '../portal/scope.ts';
import { Button } from '../ui/Button.tsx';
import { Card, EmptyState, Spinner } from '../ui/Card.tsx';
import { TextField } from '../ui/Field.tsx';
import { FilterButtons } from '../ui/FilterButtons.tsx';
import { Icon } from '../ui/Icon.tsx';
import { StatusBadge } from '../ui/StatusBadge.tsx';
import { BillingFrame } from './billing/BillingHeader.tsx';
import { ChargeForm } from './billing/ChargeForm.tsx';
import { STATUS_TONE, chargeLabel, formatMoney, useBillingData } from './billing/billing.ts';

type Filter = 'open' | 'overdue' | 'paid' | 'cancelled' | 'all';

const fold = (s: string): string =>
  s
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toLowerCase();

const MATCH: Record<Filter, (c: Charge) => boolean> = {
  open: (c) => c.status === 'POR_COBRAR' || c.status === 'PARCIAL' || c.status === 'VENCIDO',
  overdue: (c) => c.status === 'VENCIDO',
  paid: (c) => c.status === 'PAGADO',
  cancelled: (c) => c.status === 'CANCELADO',
  all: () => true,
};

/**
 * "Cobros": every charge of the clients in view, recorded or generated by a
 * retainer, with its due date, total, balance and state; new single charges.
 */
export function BillingChargesPage() {
  const { t } = useTranslation();
  const data = useBillingData();
  const names = useNames();
  const { scope } = useScope();
  const pending = usePendingIds('Cobros');
  const [, navigate] = useLocation();
  const [filter, setFilter] = useState<Filter>('open');
  const [query, setQuery] = useState('');
  const [creating, setCreating] = useState(false);

  const shown = useMemo(() => {
    const q = fold(query.trim());
    return (data?.charges ?? [])
      .filter(MATCH[filter])
      .filter(
        (c) =>
          !q ||
          fold(chargeLabel(c)).includes(q) ||
          fold(c.folioFactura ?? '').includes(q) ||
          fold(names.client(c.clienteId)).includes(q),
      )
      .sort((a, b) =>
        filter === 'open' || filter === 'overdue'
          ? a.fechaVencimiento.localeCompare(b.fechaVencimiento)
          : b.fechaEmision.localeCompare(a.fechaEmision),
      );
  }, [data, filter, query, names]);

  return (
    <BillingFrame
      tab="charges"
      title={t('billing.charges.title')}
      intro={t('billing.charges.intro')}
      actions={
        <Button
          icon="plus"
          onClick={() => {
            setCreating(true);
          }}
        >
          {t('billing.charges.new')}
        </Button>
      }
    >
      <Card>
        <div className="mb-4 space-y-3">
          <FilterButtons
            label={t('billing.charges.filterLabel')}
            value={filter}
            options={(['open', 'overdue', 'paid', 'cancelled', 'all'] as const).map((f) => ({
              value: f,
              label: t(`billing.charges.filters.${f}`),
            }))}
            onChange={setFilter}
          />
          <div className="max-w-sm">
            <TextField
              label={t('common.search')}
              type="search"
              value={query}
              onChange={(e) => {
                setQuery(e.target.value);
              }}
            />
          </div>
        </div>
        {!data ? (
          <Spinner label={t('common.loading')} />
        ) : shown.length === 0 ? (
          <EmptyState icon="list" title={t('billing.charges.empty')} />
        ) : (
          <div className="relative overflow-x-auto">
            <table className="w-full min-w-[40rem] text-sm">
              <caption className="sr-only">{t('billing.charges.title')}</caption>
              <thead>
                <tr className="border-b border-border text-left text-muted-foreground">
                  <th scope="col" className="py-2 pr-3 font-medium">
                    {t('billing.charges.table.charge')}
                  </th>
                  <th scope="col" className="py-2 pr-3 font-medium">
                    {t('billing.charges.table.due')}
                  </th>
                  <th scope="col" className="py-2 pr-3 text-right font-medium">
                    {t('billing.charges.table.total')}
                  </th>
                  <th scope="col" className="py-2 pr-3 text-right font-medium">
                    {t('billing.charges.table.balance')}
                  </th>
                  <th scope="col" className="py-2 font-medium">
                    {t('billing.charges.table.status')}
                  </th>
                </tr>
              </thead>
              <tbody>
                {shown.map((c) => (
                  <tr key={c.id} className="border-b border-border align-top last:border-0">
                    <td className="py-3 pr-3">
                      <Link
                        href={`/cobranza/cobros/${c.id}`}
                        className="font-medium underline-offset-2 hover:underline"
                      >
                        {chargeLabel(c)}
                      </Link>
                      <p className="text-muted-foreground">
                        {[
                          scope.clientId ? '' : names.client(c.clienteId),
                          c.folioFactura ?? '',
                          c.row ? '' : t('billing.charges.notSaved'),
                        ]
                          .filter(Boolean)
                          .join(' · ')}
                      </p>
                      {pending.has(c.id) ? (
                        <p className="mt-1 inline-flex items-center gap-1 text-xs text-muted-foreground">
                          <Icon name="cloudOff" className="size-3.5" />
                          {t('common.pendingSync')}
                        </p>
                      ) : null}
                    </td>
                    <td className="py-3 pr-3 whitespace-nowrap">
                      <time dateTime={c.fechaVencimiento}>{formatDate(c.fechaVencimiento)}</time>
                    </td>
                    <td className="py-3 pr-3 text-right whitespace-nowrap tabular-nums">
                      {formatMoney(c.amounts.total, c.moneda)}
                    </td>
                    <td className="py-3 pr-3 text-right whitespace-nowrap tabular-nums">
                      {formatMoney(c.saldo, c.moneda)}
                    </td>
                    <td className="py-3">
                      <StatusBadge tone={STATUS_TONE[c.status]}>
                        {c.status === 'VENCIDO'
                          ? t('billing.overdueDays', { count: c.diasVencido })
                          : t(`billing.status.${c.status}`)}
                      </StatusBadge>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Card>
      {creating && data ? (
        <ChargeForm
          honorarios={data.honorarios}
          onClose={() => {
            setCreating(false);
          }}
          onSaved={(id) => {
            navigate(`/cobranza/cobros/${id}`);
          }}
        />
      ) : null}
    </BillingFrame>
  );
}
